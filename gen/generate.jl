# Generate src/libflint/generated/*.jl from gen/inventory.toml (deterministic; run twice, no diff).
# Run: julia --project=gen gen/generate.jl
include(joinpath(@__DIR__, "inventory.jl"))

_, bindings = load_inventory()
outdir = joinpath(@__DIR__, "..", "src", "libflint", "generated")
mkpath(outdir)

# "inline" rows with `use` lists also need bindings: those targets are exports with no signature of
# their own, so they are declared in their own `export` rows (see inventory).
families = sort(unique(b.family for b in bindings))
header = "# GENERATED by gen/generate.jl from gen/inventory.toml. Do not edit.\n"
for fam in families
    open(joinpath(outdir, fam * ".jl"), "w") do io
        print(io, header)
        for b in sort(filter(b -> b.family == fam, bindings); by = b -> b.name)
            params = ["a$i" for i in eachindex(b.args)]
            tuple = isempty(b.args) ? "()" : "(" * join(b.args, ", ") * ",)"
            plist = join(params, ", ")
            call = isempty(params) ? "" : ", " * plist
            println(io, "@inline $(b.name)($plist) = ccall((:$(b.name), libflint), $(b.ret), $tuple$call)")
        end
    end
end
println("generated ", length(bindings), " bindings in ", length(families), " files")
